#!/usr/bin/env python3
import os
import sys
import json
import re
import glob
from datetime import datetime

DEFAULT_OUTPUT_PATH = os.path.expanduser("~/AI_Workflow/vault/chats/active_chat_transcript.md")

def find_latest_transcript():
    brain_dir = os.path.expanduser("~/.gemini/antigravity/brain")
    if not os.path.exists(brain_dir):
        return None
    transcripts = []
    for root, dirs, files in os.walk(brain_dir):
        for file in files:
            if file == "transcript.jsonl":
                transcripts.append(os.path.join(root, file))
    if not transcripts:
        return None
    # Sort by modification time desc
    transcripts.sort(key=lambda x: os.path.getmtime(x), reverse=True)
    return transcripts[0]

def clean_user_content(content):
    # Remove USER_REQUEST tags
    match = re.search(r'<USER_REQUEST>(.*?)</USER_REQUEST>', content, re.DOTALL)
    if match:
        req = match.group(1).strip()
    else:
        req = content.strip()
    
    # Strip any additional metadata
    req = re.sub(r'<ADDITIONAL_METADATA>.*?</ADDITIONAL_METADATA>', '', req, flags=re.DOTALL).strip()
    return req

def truncate_text(text, max_len=1200, keep_ends=500):
    if not text:
        return ""
    if len(text) <= max_len:
        return text
    return f"{text[:keep_ends]}\n\n... [TRUNCATED {len(text) - 2*keep_ends} CHARACTERS] ...\n\n{text[-keep_ends:]}"

def format_timestamp(iso_str):
    try:
        dt = datetime.strptime(iso_str, "%Y-%m-%dT%H:%M:%SZ")
        return dt.strftime("%Y-%m-%d %H:%M:%S UTC")
    except Exception:
        try:
            # Try with decimal seconds
            dt = datetime.strptime(iso_str.split('.')[0], "%Y-%m-%dT%H:%M:%S")
            return dt.strftime("%Y-%m-%d %H:%M:%S UTC")
        except Exception:
            return iso_str

def main():
    input_file = None
    output_file = DEFAULT_OUTPUT_PATH

    if len(sys.argv) > 1:
        input_file = sys.argv[1]
    if len(sys.argv) > 2:
        output_file = sys.argv[2]

    if not input_file:
        input_file = find_latest_transcript()
        if not input_file:
            print("Error: No transcript.jsonl found and no path provided.")
            sys.exit(1)

    print(f"Reading transcript from: {input_file}")
    print(f"Writing Markdown output to: {output_file}")

    if not os.path.exists(input_file):
        print(f"Error: Input file {input_file} does not exist.")
        sys.exit(1)

    # Ensure output directory exists
    os.makedirs(os.path.dirname(output_file), exist_ok=True)

    markdown_lines = []
    markdown_lines.append("# Active Chat Transcript (Cross-Agent Continuity)")
    markdown_lines.append(f"> Auto-generated by `sync-chat.py` on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    markdown_lines.append("> Shared dialogue persistent context. Read this file at session start to catch up.")
    markdown_lines.append("")

    with open(input_file, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            try:
                step = json.loads(line)
            except Exception as e:
                print(f"Warning: Failed to parse line: {e}")
                continue

            step_type = step.get("type")
            source = step.get("source")
            content = step.get("content", "")
            created_at = format_timestamp(step.get("created_at", ""))
            step_idx = step.get("step_index", "?")

            if source == "USER_EXPLICIT" and step_type == "USER_INPUT":
                cleaned = clean_user_content(content)
                markdown_lines.append(f"## 👤 User (at {created_at}) [Step {step_idx}]")
                markdown_lines.append(cleaned)
                markdown_lines.append("")
                markdown_lines.append("---")
                markdown_lines.append("")

            elif source == "MODEL" and step_type == "PLANNER_RESPONSE":
                if content:
                    markdown_lines.append(f"## 🤖 Antigravity Agent (at {created_at}) [Step {step_idx}]")
                    markdown_lines.append(content)
                    markdown_lines.append("")
                
                tool_calls = step.get("tool_calls", [])
                if tool_calls:
                    markdown_lines.append("### 🛠️ Tool Calls")
                    for tc in tool_calls:
                        name = tc.get("name")
                        args = tc.get("args", {})
                        # Render tool arguments in clean format
                        args_str = json.dumps(args, indent=2)
                        markdown_lines.append(f"- **Tool**: `{name}`")
                        markdown_lines.append("  ```json")
                        # Add indent to args json
                        for line_args in args_str.split("\n"):
                            markdown_lines.append(f"  {line_args}")
                        markdown_lines.append("  ```")
                    markdown_lines.append("")
                markdown_lines.append("---")
                markdown_lines.append("")

            elif source == "SYSTEM" and step_type in ["RUN_COMMAND", "VIEW_FILE", "LIST_DIRECTORY", "GREP_SEARCH", "CODE_ACTION", "GENERIC"]:
                # Render tool results in details block
                truncated = truncate_text(content)
                markdown_lines.append(f"#### 📦 Tool Result: {step_type} [Step {step_idx}]")
                markdown_lines.append("<details>")
                markdown_lines.append(f"<summary>View Tool Output ({len(content)} bytes)</summary>")
                markdown_lines.append("")
                markdown_lines.append("```text")
                markdown_lines.append(truncated)
                markdown_lines.append("```")
                markdown_lines.append("</details>")
                markdown_lines.append("")
                markdown_lines.append("---")
                markdown_lines.append("")

    with open(output_file, "w", encoding="utf-8") as out:
        out.write("\n".join(markdown_lines))

    print("Synchronization complete!")

if __name__ == "__main__":
    main()
